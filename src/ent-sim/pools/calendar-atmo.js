// 获取特定日期的氛围（dayCount → month-day → 氛围文本）
export function getCalendarAtmo(dayCount) {
  // 内联日历计算（避免循环import）
  var rem = (dayCount || 1) - 1;
  var y = 2024;
  while (true) {
    var diy = (y % 4 === 0 && y % 100 !== 0) || (y % 400 === 0) ? 366 : 365;
    if (rem < diy) break;
    rem -= diy;
    y++;
  }
  var dimArr = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  var m = 1;
  for (var i = 0; i < 12; i++) {
    var dim = dimArr[i];
    if (i === 1 && ((y % 4 === 0 && y % 100 !== 0) || (y % 400 === 0))) dim = 29;
    if (rem < dim) break;
    rem -= dim;
    m++;
  }
  var d = rem + 1;
  var monthPool = CALENDAR_ATMO_POOL[m];
  if (!monthPool) return '';
  return monthPool[d] || '';
}
