// 获取当前节点的方向+禁忌文本
export function getMainlineAnchor(nodeId) {
  if (!nodeId) return '';
  var anchor = MAINLINE_ANCHORS[nodeId];
  if (!anchor) return '';
  return '【本回合方向】' + anchor.direction + '\n【本回合禁忌】' + anchor.ban;
}

// 获取当前阶段的禁忌清单
export function getMainlineBanList(stage) {
  if (stage === undefined || stage === null) stage = 0;
  return MAINLINE_BAN_LISTS[stage] || '';
}
