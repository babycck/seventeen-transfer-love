// 按人气档位推荐结局前置类型
export function pickEndingPrelude(popularity, affection, isHappy) {
  if (!ENDING_PRELUDE_POOL.length) return null;
  var cat = 'any';
  if (popularity < 20) cat = isHappy ? 'low_he' : 'low_be';
  else if (popularity < 50) cat = isHappy ? 'mid_he' : 'mid_ne';
  else cat = isHappy ? 'high_he' : 'high_be';
  var pool = ENDING_PRELUDE_POOL.filter(function(e) { return e.cat === cat || e.cat === 'any'; });
  return pool[Math.floor(Math.random() * pool.length)];
}
