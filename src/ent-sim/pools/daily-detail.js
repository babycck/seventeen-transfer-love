// 按场景类型过滤，返回匹配的条目列表（无匹配时返回通用型）
export function filterDailyDetail(scene) {
  if (!DAILY_DETAIL_POOL || !DAILY_DETAIL_POOL.length) return [];
  var matched = [];
  var generic = [];
  for (var i = 0; i < DAILY_DETAIL_POOL.length; i++) {
    var item = DAILY_DETAIL_POOL[i];
    if (item.scene === scene) matched.push(item);
    if (item.scene === '通用') generic.push(item);
  }
  // 优先返回场景匹配的，无匹配则返回通用池
  return matched.length ? matched : generic;
}

// 随机抽取一条
export function pickDailyDetail(scene) {
  var pool = filterDailyDetail(scene);
  if (!pool.length) return '';
  return pool[Math.floor(Math.random() * pool.length)].text;
}
